function normalizeText(value) {
  return value === null || value === undefined ? '' : String(value).trim()
}

function matchRule(name, rules) {
  const text = normalizeText(name)
  if (!text) {
    return ''
  }
  const matched = rules.find((rule) => rule.keywords.some((keyword) => text.includes(keyword)))
  return matched ? matched.name : ''
}

export function classifyEightDim(name) {
  return matchRule(name, eightDimRules) || '其他'
}

export function classifyIndustry(name) {
  return matchRule(name, industryRules) || '其他产业'
}

export function classifyView(name, viewMode) {
  const eightDim = classifyEightDim(name)
  if (viewMode === 'industry') {
    if (eightDim !== '产业') {
      return ''
    }
    return classifyIndustry(name)
  }
  return eightDim
}

export function summarizeFlowRows(rows, viewMode) {
  const summaryMap = new Map()

  rows.forEach((row) => {
    const etfName = row.etfName ?? row.etf_name ?? ''
    const category = classifyView(etfName, viewMode)
    if (!category) {
      return
    }

    const etfCode = row.etfCode ?? row.etf_code ?? ''
    const dailyFlow = Number(row.fundFlow ?? row.fund_flow ?? 0) || 0
    const cumulativeFlow = Number(row.cumulativeFlow ?? row.cumulative_flow ?? 0) || 0
    const current = summaryMap.get(category) || {
      category,
      etfCountSet: new Set(),
      dailyFlow: 0,
      cumulativeFlow: 0
    }

    current.etfCountSet.add(etfCode)
    current.dailyFlow += dailyFlow
    current.cumulativeFlow += cumulativeFlow
    summaryMap.set(category, current)
  })

  return Array.from(summaryMap.values())
    .map((item) => ({
      category: item.category,
      etfCount: item.etfCountSet.size,
      dailyFlow: Number(item.dailyFlow.toFixed(2)),
      cumulativeFlow: Number(item.cumulativeFlow.toFixed(2))
    }))
    .sort((left, right) => Math.abs(right.dailyFlow) - Math.abs(left.dailyFlow))
}